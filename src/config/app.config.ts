export const dnaDots = Array.from({ length: 28 }, (_, index) => {
  const progress = index / 27;
  const wave = Math.sin(progress * Math.PI * 4);
  const size = 0.55 + Math.cos(progress * Math.PI * 4) * 0.12;

  return {
    id: index,
    top: `${5 + progress * 90}%`,
    left: `${50 + wave * 15}%`,
    right: `${50 - wave * 15}%`,
    size: `${size}rem`,
    opacity: 0.62 + Math.abs(wave) * 0.26,
  };
});

